def get(prompt_id: str) -> str:
    """按 id 返回 prompt 文本。未知 id 立即报错，杜绝静默回退到旧文本。"""
    try:
        return PROMPTS[prompt_id]["text"]
    except KeyError:
        raise KeyError(f"unknown prompt id: {prompt_id!r}; register it in prompts_registry.PROMPTS first") from None


def get_version(prompt_id: str) -> str:
    """按 id 返回版本号。"""
    try:
        return PROMPTS[prompt_id]["version"]
    except KeyError:
        raise KeyError(f"unknown prompt id: {prompt_id!r}") from None


def ids() -> tuple[str, ...]:
    """全部已注册 prompt id（稳定顺序）。"""
    return tuple(PROMPTS)


def load_manifest() -> dict:
    """加载同目录 prompts_manifest.json，供追溯性校验使用。"""
    path = Path(__file__).with_name("prompts_manifest.json")
    return json.loads(path.read_text(encoding="utf-8"))
